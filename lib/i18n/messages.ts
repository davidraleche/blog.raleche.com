/** Replace {name} placeholders. */
export function fmt(s: string, vars: Record<string, string | number> = {}) {
  // A missing key gives "" instead of crashing the page.
  return (s ?? "").replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

